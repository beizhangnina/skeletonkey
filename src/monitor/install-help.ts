/**
 * `skeletonkey monitor install-help` (ND-5): PRINTS example scheduler snippets
 * for a weekly `monitor run`. SkeletonKey never installs a cron job, a
 * launchd plist, or a systemd timer itself -- a human copies one of these in,
 * on purpose, so nothing runs on a schedule without them choosing to.
 */

export function monitorInstallHelpText(skeletonkeyBin = "skeletonkey"): string {
  return [
    "SkeletonKey never installs a scheduled job itself. Copy whichever of these",
    "fits your machine and install it yourself.",
    "",
    "--- cron (Linux/macOS), every Monday at 09:00 local time -------------------",
    "",
    `  0 9 * * 1 ${skeletonkeyBin} monitor run >> ~/.skeletonkey/monitor/cron.log 2>&1`,
    "",
    "  Install with: crontab -e, then paste the line above.",
    "",
    "--- systemd timer (Linux) ---------------------------------------------------",
    "",
    "  ~/.config/systemd/user/skeletonkey-monitor.service:",
    "    [Unit]",
    "    Description=SkeletonKey weekly monitor",
    "",
    "    [Service]",
    "    Type=oneshot",
    `    ExecStart=${skeletonkeyBin} monitor run`,
    "",
    "  ~/.config/systemd/user/skeletonkey-monitor.timer:",
    "    [Unit]",
    "    Description=Run the SkeletonKey weekly monitor",
    "",
    "    [Timer]",
    "    OnCalendar=Mon *-*-* 09:00:00",
    "    Persistent=true",
    "",
    "    [Install]",
    "    WantedBy=timers.target",
    "",
    "  Install with:",
    "    systemctl --user daemon-reload",
    "    systemctl --user enable --now skeletonkey-monitor.timer",
    "",
    "--- launchd (macOS) ----------------------------------------------------------",
    "",
    "  ~/Library/LaunchAgents/run.skeletonkey.monitor.plist:",
    '    <?xml version="1.0" encoding="UTF-8"?>',
    '    <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"',
    '      "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '    <plist version="1.0">',
    "    <dict>",
    "      <key>Label</key><string>run.skeletonkey.monitor</string>",
    "      <key>ProgramArguments</key>",
    "      <array>",
    `        <string>${skeletonkeyBin}</string>`,
    "        <string>monitor</string>",
    "        <string>run</string>",
    "      </array>",
    "      <key>StartCalendarInterval</key>",
    "      <dict>",
    "        <key>Weekday</key><integer>1</integer>",
    "        <key>Hour</key><integer>9</integer>",
    "        <key>Minute</key><integer>0</integer>",
    "      </dict>",
    "    </dict>",
    "    </plist>",
    "",
    "  Install with: launchctl load ~/Library/LaunchAgents/run.skeletonkey.monitor.plist",
    "",
    "None of the above was written or touched by this command -- it only printed.",
  ].join("\n");
}
